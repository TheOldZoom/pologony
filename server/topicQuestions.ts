function shuffledDeck(topic: keyof typeof banks): number[] {
  if (topic === 'chess') {
    const puzzleCount = chessPuzzles.length + chessLines.length;
    const puzzles = shuffle(
      Array.from({ length: puzzleCount }, (_, index) => chess.length + index),
    );
    const trivia = shuffle(chess.map((_, index) => index)).slice(0, Math.ceil(puzzleCount / 3));
    return trivia.flatMap((index, group) => [...puzzles.slice(group * 3, group * 3 + 3), index]);
  }
  if (topic !== 'history') return shuffle(banks[topic].map((_, index) => index));
  let offset = 0;
  const sample = historyBanks.flatMap((bank) => {
    const indices = bank.map((_, index) => offset + index);
    offset += bank.length;
    return shuffle(indices).slice(0, 8);
  });
  return shuffle(sample);
}

